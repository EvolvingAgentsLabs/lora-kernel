"""Acceptance as ranking, measured for the first time — on experts graded by construction.

THE CLAIM UNDER TEST. The architecture says a small expert's **acceptance rate against
a larger target** orders experts the way verified quality orders them, so a pool can
be ranked with no judge. `REPORT.md` §6 records that this is the *only* claim that
survives the existence of EAGLE-3 — a purpose-built head wins latency outright and
cannot rank anything. And `docs/RECORD.md` §2 (and `docs/analysis/generated-code-ceiling.md` at the tag `v0.1-foundations`) records why it has
never been tested: **ranking needs experts that differ in quality**, and this project
has had one useful expert. `graded.py` makes three from one corpus.

WHAT IS MEASURED, EXACTLY. Every model here shares one tokenizer with the target
**[ran]** P48, so for the first time acceptance is defined in **tokens** rather than
characters. At temperature 0 the target is one-hot, so speculative decoding's test —
accept with probability min(1, p_target / p_draft) — reduces to *is the drafted token
the target's argmax*. The target is asked for `prompt_logprobs` over the draft it is
handed, and a token is accepted iff its rank under the target is 1. **Nothing is
sampled; nothing is generated by the target during scoring.** One prefill per span.

WHY THE DRAFTER IS SERVED IN CORPUS MODE. `email-full` was trained on transcripts where
a call is immediately followed by its answer — `<tag>…</tag>= {result}` — and served
through `tool_calls` it cannot receive an answer mid-generation, so it **invents one**:
P43's records show `= {"turns": 1, "i_wrote_in_thread": false}` written by the expert
where the tool said `turns: 2, true` **[ran]** `results/P43-openclaw-e2e-20260915/`.
Every later decision in that chain rests on a fact it made up. Scored by a target,
those invented spans would be rejected wholesale, and how much a grade invents is not
its quality. So here the loop is the harness's: generate to `</tag>`, stop, inject the
**real** result, continue. The draft is then the expert's decisions on real facts, and
the same transcript can be handed to the target verbatim.

WHERE THE SIGNAL CAN LIVE, AND WHY IT IS REPORTED IN THREE PLACES. A chain is ~40
tokens of which the verdict is one or two. Acceptance weights every token equally, so
two experts that differ only in verdicts would differ in α by a few percent — and a
result saying "α does not rank" could mean the mechanism fails or that the quality
lives in a token α barely sees. Both are findings; they are different findings. So α
is reported over **all decision tokens** (primary, pre-registered), over the **tag
spans** and over the **verdict span** separately, so the report can say where the
agreement was.

THE HARNESS-SUPPLIED TEXT IS NEVER SCORED. `= {result}` lines are injected by this
loop, exactly as a serving harness would inject them; they sit in the target's prefix
and in no span. Scoring them would score the tool.

    # session A — the instrument, on the expert that exists; no training
    python3 -m training.harness.accept_rank --stage all \\
        --adapter email-full=adapters/email-full --target Qwen/Qwen2.5-32B-Instruct-AWQ
    # session B+C — the graded experts, gated before the target is served
    python3 -m training.harness.accept_rank --stage all \\
        --train g75=training/harness/data_ef/train_g75.jsonl \\
        --train g200=training/harness/data_ef/train_g200.jsonl \\
        --adapter email-full=adapters/email-full --target Qwen/Qwen2.5-32B-Instruct-AWQ
"""

