def user_text(msg: dict) -> str:
    """The user turn, byte for byte what the corpus generator wrote."""
    return f"{listing(msg)}\n\n{INSTRUCTION}"


# THE ARITY CONVENTION, ON THE WAY IN. P28 renders a single-required-parameter tool
# as `<tag>...</tag>`, so a model that follows the block writes `<thread_history>
# thr-003</thread_history>` — positionally, as told. `agent_sim` maps that body onto
# the parameter's name before the tool sees it; the first version of this loop did
# not, and the untrained 32B had 749 of 1243 calls refused with "is not key=value"
# for obeying the instruction it was given **[ran]** 2026-09-17,
# `session_a_attempt2_positional.json`. Keyed on a COUNT, never on a name.
POSITIONAL = {t["function"]["name"]: (t["function"]["parameters"].get("required")
                                      or sorted(t["function"]["parameters"]["properties"]))[0]
              for t in SCHEMA
              if len(t["function"]["parameters"].get("required")
                     or t["function"]["parameters"]["properties"]) == 1}


def keyed(tool: str, body: str, positional: dict | None = None) -> str:
    """A positional body becomes `param=body` when the tool has exactly one parameter."""
    pos = POSITIONAL if positional is None else positional
    b = body.strip()
    if "=" not in b and tool in pos and b:
        return f"{pos[tool]}={b}"
    return body


def parse_verdict(text: str):
    t = text.upper()
    if "NOT IMPORTANT" in t:
        return False
    if "IMPORTANT" in t:
        return True
    return None


def run_chain(gen, inbox: dict, max_calls: int = 6, suite=None) -> dict:
    """Generate, stop at every closing tag, answer it for real, continue.

    `gen(prefix)` returns the model's continuation after `prefix` (the assistant
    text so far). It is the whole harness, the shape `physics.calc` already has.
    `suite` decides the tags, the tools and the verdict rule; the default is triage.
    """
    close = suite.close if suite else CLOSE
    tag = suite.tag if suite else TAG
    tool = suite.answer if suite else answer
    pos = suite.positional if suite else POSITIONAL
    parse = suite.parse if suite else parse_verdict
    out, spans, calls, refused, stray, malformed = "", [], 0, 0, 0, 0
    for _ in range(max_calls + 1):
        chunk = gen(out)
        # TRUST THE STOP STRING ONLY AS FAR AS IT GOES. Anything past the first
        # closing tag is the model guessing an answer it was told to ask for.
        cuts = [chunk.index(c) + len(c) for c in close if c in chunk]
        cut = min(cuts) if cuts else None
        if cut is not None:
            chunk = chunk[:cut]
        # A `= …` LINE THE MODEL WROTE ITSELF is the invented result P43 saw. It is
        # kept in the span — the target will reject it, which is the point — and
        # counted, so the report can say how often a grade still does it.
        stray += sum(1 for line in chunk.splitlines() if line.lstrip().startswith("="))
        spans.append({"at": len(out), "text": chunk})
        out += chunk
        if cut is None:
            break
        calls += 1
        matches = list(tag.finditer(out))
        # A CLOSING TAG WITH NO CANONICAL OPENING is a malformed call, not a crash.
        # `g25` wrote `<message id=msg-003>…</message>` — the XML-attribute form —
        # and the first version of this loop died on `[-1]` of an empty match list
        # for 209 of 240 cases, recording no text at all **[ran]** P58. The model is
        # told, as it is told about a refused call, and the chain continues.
        if not matches or matches[-1].end() != len(out):
            refused += 1
            malformed += 1
            out += "= ERROR: malformed call — write <tag>key=value</tag>\n"
            continue
        m = matches[-1]                           # the call just closed
        try:
            res = tool(inbox, m.group(1), keyed(m.group(1), m.group(2), pos))
        except ToolError as e:
            refused += 1
            res = f"ERROR: {e}"
        out += f"= {res}\n"
    finished = cut is None
    return {"text": out, "spans": spans, "calls": calls, "refused": refused,
            "malformed": malformed, "stray_results": stray,
            "verdict": parse(spans[-1]["text"]) if finished else None,
            "ran_out": not finished}


# --- serving -------------------------------------------------------------------

def post(path: str, payload: dict, timeout: int = 300) -> dict:
    req = urllib.request.Request(HOST + path, method="POST",
                                 data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.load(r)


def serve(model: str, extra: list[str]) -> subprocess.Popen:
    cmd = ["vllm", "serve", model, "--port", "8000", *extra]
    print(f"[rank] {' '.join(cmd)}", flush=True)
    return subprocess.Popen(cmd, stdout=open("vllm.log", "a"), stderr=subprocess.STDOUT)


def wait_ready(proc, minutes: int = 25) -> bool:
    deadline = time.time() + minutes * 60
    while time.time() < deadline:
        if proc.poll() is not None:
            print(f"[rank] the server exited with {proc.returncode}", flush=True)
            return False
        try:
            urllib.request.urlopen(HOST + "/health", timeout=5).read()
            return True
        except Exception:
            time.sleep(5)
    print("[rank] the server never answered /health", flush=True)
    return False


def stop(proc) -> None:
    proc.terminate()
    try:
        proc.wait(timeout=90)
    except subprocess.TimeoutExpired:
        proc.kill()


def completion(model: str, prompt: str, max_tokens: int, close=CLOSE) -> str:
    r = post("/v1/completions", {
        "model": model, "prompt": prompt, "temperature": 0, "max_tokens": max_tokens,
        "stop": list(close), "include_stop_str_in_output": True})
    ch = r["choices"][0]
    text = ch.get("text") or ""
    # BELT AND BRACES ON THE STOP STRING. If the server honoured `stop` but not
    # `include_stop_str_in_output`, `stop_reason` still names the tag it stopped at.
    reason = ch.get("stop_reason")
    if isinstance(reason, str) and reason in close and not text.endswith(reason):
        text += reason
    return text


def stop_check(model: str, prompt: str) -> dict:
    """Does the server stop at a string and hand it back? Tested on a continuation
    the model cannot avoid, so the check cannot fail on the model's phrasing.

    THE FIRST VERSION ASKED THE MODEL TO WRITE A TAG under the triage system prompt.
    The bare base answered `NOT IMPORTANT` — no tag, so no stop, so `stop_included:
    false` — and session A stopped on a check that was measuring the base's
    willingness to write a tag rather than the server's handling of `stop`
    **[ran]** 2026-09-17, one A100 boot for nothing. This one asks it to count and
    stops at `3`: the mechanism, not the model.
    """
    r = post("/v1/completions", {
        "model": model, "prompt": prompt + "1, 2, ", "temperature": 0, "max_tokens": 12,
        "stop": ["3"], "include_stop_str_in_output": True})
    ch = r["choices"][0]
    text = ch.get("text") or ""
    return {"stop_included": text.endswith("3"),
            "stop_reason": ch.get("stop_reason"), "sample": text[:40]}


def preflight(model: str, tok, kind: str) -> dict:
    """One request of each shape before 475 of them. P27 sent 240 that all failed."""
    prompt = tok.apply_chat_template(
        [{"role": "system", "content": "You count."},
         {"role": "user", "content": "Count from 1 to 6, comma separated."}],
        tokenize=False, add_generation_prompt=True)
    out = {"kind": kind}
    if kind in ("draft", "both"):
        chk = stop_check(model, prompt)
        # EITHER PATH IS FINE. A server that returns the stop string, or one that
        # withholds it but names it in `stop_reason` — `completion()` handles both.
        out["stop_included"] = chk["stop_included"] or chk["stop_reason"] == "3"
        out["stop_detail"] = chk
    if kind in ("accept", "both"):
        r = post("/v1/completions", {"model": model, "prompt": prompt + "1, 2, 3",
                                     "max_tokens": 1, "temperature": 0,
                                     "prompt_logprobs": 1})
        pl = (r["choices"][0].get("prompt_logprobs") or [])
        n = len(tok(prompt + "1, 2, 3")["input_ids"])
        out["prompt_logprobs_len"] = len(pl)
        out["prompt_tokens"] = n
        out["shape_ok"] = (len(pl) == n and pl[0] is None
                           and all(isinstance(d, dict) and all("rank" in v for v in d.values())
                                   for d in pl[1:]))
    print(f"[rank] preflight {kind}: {json.dumps(out)[:200]}", flush=True)
    return out


# --- the two stages --------------------------------------------------------------

def draft_arm(model: str, tok, suite, cases: list, max_tokens: int, concurrency: int,
              done: dict, checkpoint) -> list[dict]:
    """Every case through the corpus-mode loop, persisted as it lands."""
    todo = [c for c in cases if c.id not in done]
    print(f"[rank] arm {model}: {len(todo)} to draft, {len(done)} resumed", flush=True)

    def one(case):
        base_prompt = tok.apply_chat_template(
            [{"role": "system", "content": suite.system},
             {"role": "user", "content": suite.user_text(case)}],
            tokenize=False, add_generation_prompt=True)
        try:
            chain = run_chain(lambda prefix: completion(model, base_prompt + prefix,
                                                        max_tokens, suite.close),
                              case.ctx, max_calls=getattr(suite, "max_calls", 6), suite=suite)
        except Exception as e:                      # transport, never folded into a score
            return {"id": case.id, "error": repr(e)[:160]}
        return {"id": case.id, "human": case.human, "truth": case.truth,
                "correct": bool(case.verify(chain["verdict"])), **case.meta,
                "prompt_sha": hashlib.sha256(base_prompt.encode()).hexdigest()[:16],
                **chain}

    t0, n = time.time(), 0
    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        for f in as_completed([ex.submit(one, c) for c in todo]):
            rec = f.result()
            done[rec["id"]] = rec
            n += 1
            if n % 25 == 0 or n == len(todo):
                checkpoint()
                ok = sum(r.get("correct", False) for r in done.values())
                print(f"[rank] arm {model} {len(done)}/{len(cases)} correct {ok} "
                      f"{time.time() - t0:.0f}s", flush=True)
    checkpoint()
    return [done[c.id] for c in cases if c.id in done]


def accepted_flags(prompt_logprobs: list, ids: list[int], start: int) -> list[bool]:
    """Per drafted token: is it the target's rank-1 token at that position?"""
    flags = []
    for i in range(start, len(ids)):
        d = prompt_logprobs[i] or {}
        entry = d.get(ids[i]) or d.get(str(ids[i]))
        flags.append(bool(entry) and entry.get("rank") == 1)
    return flags


def score_span(model: str, tok, prefix: str, span: str) -> dict:
    ids_p = tok(prefix)["input_ids"]
    ids_a = tok(prefix + span)["input_ids"]
    # THE BOUNDARY CAN MERGE. BPE may fuse the last prefix token with the first span
    # token; the span then starts where the two id lists diverge, and the shift is
    # counted rather than hidden.
    k = 0
    while k < len(ids_p) and k < len(ids_a) and ids_p[k] == ids_a[k]:
        k += 1
    r = post("/v1/completions", {"model": model, "prompt": prefix + span,
                                 "max_tokens": 1, "temperature": 0, "prompt_logprobs": 1})
    pl = r["choices"][0].get("prompt_logprobs") or []
    if len(pl) != len(ids_a):
        return {"error": f"prompt_logprobs {len(pl)} != tokens {len(ids_a)}"}
    flags = accepted_flags(pl, ids_a, k)
    lcp = next((i for i, f in enumerate(flags) if not f), len(flags))
    return {"tokens": len(flags), "accepted": sum(flags), "lcp": lcp,
            "shift": len(ids_p) - k, "flags": flags}


def accept_arm(model: str, tok, suite, cases: list, drafts: list[dict], concurrency: int,
               done: dict, checkpoint) -> list[dict]:
    by_id = {c.id: c for c in cases}
    todo = [d for d in drafts if d["id"] not in done and "spans" in d]
    print(f"[rank] accept {len(todo)} drafts, {len(done)} resumed", flush=True)

    def one(d):
        case = by_id[d["id"]]
        base_prompt = tok.apply_chat_template(
            [{"role": "system", "content": suite.system},
             {"role": "user", "content": suite.user_text(case)}],
            tokenize=False, add_generation_prompt=True)
        if hashlib.sha256(base_prompt.encode()).hexdigest()[:16] != d.get("prompt_sha"):
            return {"id": d["id"], "error": "the prompt is not the one the draft saw"}
        scored = []
        for s in d["spans"]:
            if not s["text"]:
                continue
            try:
                scored.append(score_span(model, tok, base_prompt + d["text"][:s["at"]],
                                         s["text"]))
            except Exception as e:
                scored.append({"error": repr(e)[:160]})
        return {"id": d["id"], "spans": scored, **alpha_of(scored)}

    n = 0
    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        for f in as_completed([ex.submit(one, d) for d in todo]):
            rec = f.result()
            done[rec["id"]] = rec
            n += 1
            if n % 25 == 0 or n == len(todo):
                checkpoint()
                print(f"[rank] accept {len(done)}/{len(drafts)}", flush=True)
    checkpoint()
    return [done[d["id"]] for d in drafts if d["id"] in done]


def alpha_of(scored: list[dict]) -> dict:
    """α over all decision tokens, over the tag spans, over the verdict span."""
    ok = [s for s in scored if "tokens" in s]
    if not ok or any("error" in s for s in scored):
        return {"alpha": None, "alpha_tags": None, "alpha_verdict": None,
                "errors": sum("error" in s for s in scored)}
    tot = sum(s["tokens"] for s in ok)
    acc = sum(s["accepted"] for s in ok)
    tags, last = ok[:-1], ok[-1]
    ttot = sum(s["tokens"] for s in tags)
    return {
        "alpha": acc / tot if tot else None,
        "alpha_tags": (sum(s["accepted"] for s in tags) / ttot) if ttot else None,
        "alpha_verdict": last["accepted"] / last["tokens"] if last["tokens"] else None,
        "alpha_lcp": sum(s["lcp"] for s in ok) / tot if tot else None,
        "tokens": tot, "errors": 0,
    }


# --- gates, as code -------------------------------------------------------------

def applied(base: list[dict], adapter: list[dict], n: int = PROBE) -> dict:
    """C18: an adapter vLLM loaded and did not apply serves the base's text."""
    # AN ERRORED RECORD IS NOT A DIFFERENCE. P58's g25 arm failed 209 of 240 requests,
    # its records carried `text: None`, and this gate read None ≠ text as "differs" on
    # 8 of 8 probes — `applied` over an arm that had produced nothing **[ran]**. A
    # check that passes while the capability is broken; only records with a text on
    # both sides are probed, and too few of them is its own verdict.
    b = {r["id"]: r["text"] for r in base if (r.get("text") or "").strip() and "error" not in r}
    a = {r["id"]: r["text"] for r in adapter if (r.get("text") or "").strip() and "error" not in r}
    ids = sorted(set(a) & set(b))[:n]
    differs = sum(a[i] != b[i] for i in ids)
    # EMPTY IS NOT A DIFFERENCE EITHER: an adapter answering "" on every probe reads
    # as `differs` against any base text, and would have called itself applied.
    if len(ids) < 3:
        return {"probed": len(ids), "differs": differs,
                "verdict": f"UNREADABLE: only {len(ids)} probes with non-empty text on both sides"}
    return {"probed": len(ids), "differs": differs,
            "verdict": "applied" if differs else "NOT APPLIED: identical to the base"}


def _map(records: list[dict], key: str = "correct", human_only: bool = True) -> dict:
    return {r["id"]: r[key] for r in records
            if key in r and "error" not in r and (r.get("human") or not human_only)}


def target_gate(target: list[dict], expert: list[dict], majority_bar: float) -> dict:
    """The skill's trap: verify against something not stronger and a high α means
    *drifted least*. FOUNDATIONS §7.2 states the precondition as Q(T) >= max Q(E), and
    the gate follows it literally since 2026-09-17: the target must be **not
    resolvably worse** than the best expert on the same cases, with a total at least
    the expert's. The first version demanded a resolvable *win*, which no target can
    produce against an expert at the ceiling — a tie at the ceiling is a result, not a
    failure of the gate. Neither verdict taken so far changes (2 : 87 and 0 : 8 are
    losses under both rules)."""
    c = bar.compare(_map(target), _map(expert))
    t_acc = c["a_total"] / c["n_paired"] if c["n_paired"] else 0.0
    worse = c["different"] and c["only_b"] > c["only_a"]
    bought = (not worse) and c["a_total"] >= c["b_total"] and t_acc > majority_bar and c["n_paired"] > 0
    ceiling = bought and not c["different"] and c["b_total"] == c["n_paired"]
    return {**c, "target_human_accuracy": round(t_acc, 4), "majority_bar": majority_bar,
            "bought": bought, "tie_at_ceiling": ceiling,
            "reading": ("BOUGHT at the ceiling: the target ties an expert at 1.000 — Q(T) >= max Q(E) holds"
                        if ceiling else
                        "BOUGHT: Q(T) >= max Q(E) on paired cases" if bought else
                        "UNBOUGHT: the target is resolvably worse than the expert — "
                        "acceptance against it would measure similarity, not quality" if worse else
                        "UNBOUGHT: the target's total is below the expert's, or below the bar")}


def grades_gate(arms: dict[str, list[dict]], order: list[str]) -> dict:
    """Are the grades grades? Each adjacent and outer pair, paired on the same cases."""
    pairs = []
    for i in range(len(order)):
        for j in range(i + 1, len(order)):
            lo, hi = order[i], order[j]
            c = bar.compare(_map(arms[hi]), _map(arms[lo]))
            better = hi if c["only_a"] > c["only_b"] else lo
            pairs.append({"pair": [lo, hi], "resolved": c["different"],
                          "better": better if c["different"] else None, **c})
    resolved = [p for p in pairs if p["resolved"]]
    inverted = [p for p in resolved if p["better"] != p["pair"][1]]
    return {"pairs": pairs, "resolved": len(resolved), "inverted": len(inverted),
            "proceed": len(resolved) >= 1,
            "reading": (f"{len(resolved)} of {len(pairs)} pairs resolved by the verifier"
                        + (f"; {len(inverted)} INVERTED (more data scored lower)" if inverted else "")
                        + ("" if resolved else " — the grades are not grades; "
                           "nothing to rank and the target is not served"))}


def ranking_verdict(gate: dict, alphas: dict[str, list[dict]], key: str = "alpha") -> dict:
    """For every pair the verifier resolved: does α order it the same way?"""
    rows = []
    for p in gate["pairs"]:
        if not p["resolved"]:
            continue
        lo, hi = p["pair"]
        better, worse = p["better"], (lo if p["better"] == hi else hi)
        a = _map(alphas[better], key, human_only=False)
        b = _map(alphas[worse], key, human_only=False)
        ids = [i for i in set(a) & set(b) if a[i] is not None and b[i] is not None]
        up = sum(a[i] > b[i] for i in ids)
        down = sum(a[i] < b[i] for i in ids)
        pv = bar.sign_test(up, down)
        state = ("agrees" if pv <= 0.05 and up > down else
                 "DISAGREES" if pv <= 0.05 and down > up else "unresolved")
        rows.append({"pair": [worse, better], "verifier_prefers": better,
                     "alpha_higher": up, "alpha_lower": down, "ties": len(ids) - up - down,
                     "p_value": round(pv, 5), "state": state,
                     "mean_alpha": {better: _mean(a.values()), worse: _mean(b.values())}})
    states = [r["state"] for r in rows]
    verdict = ("SUPPORTED" if rows and all(s == "agrees" for s in states) else
               "FALSIFIED" if "DISAGREES" in states else
               "UNRESOLVED" if rows else "NOTHING TO RANK")
    return {"key": key, "pairs": rows, "verdict": verdict}


def _mean(xs) -> float | None:
    xs = [x for x in xs if x is not None]
    return round(sum(xs) / len(xs), 4) if xs else None


